import assert from 'node:assert/strict';
import { createJiti } from 'jiti';
const jiti = createJiti(import.meta.url);
const { buildCustomerManagementInsights: build } = await jiti.import('../src/lib/customer-management-insights.ts');
const doc = (clientKey, date, revenueCents = 10000, profitCents = 2000) => ({clientKey, date, revenueCents, profitCents});
const base = {today:'2026-10-20', dateFrom:'2026-10-01', dateTo:'2026-10-20', documents:[], cases:[], clientKeys:['a','b','lead']};
const get = (input, id) => build({...base, ...input}).find(i=>i.id===id);
const cohort = [doc('a','2025-10-10'), doc('a','2025-10-10'), doc('b','2025-10-11'), doc('b','2026-01-01'), doc('late','2025-10-12'), doc('late','2026-10-20'), doc('young','2026-10-01')];
const retention = get({documents:cohort}, 'first-return');
assert.match(retention.evidence, /: 3 чел/);
assert.match(retention.evidence, /365 дней: 1 \(33%\)/);
assert.deepEqual(retention.actions[0].clientKeys,['a','late'], 'same-day documents and return after 365 days are not retention');
assert.deepEqual(retention.actions[1].clientKeys,['b']);
assert.match(retention.limitation,/Малая выборка/);
const comparison = get({documents:[doc('a','2026-09-11',20000),doc('b','2026-09-30',20000),doc('a','2026-10-01',10000),doc('future','2026-10-21',900000)]}, 'revenue-change');
assert.match(comparison.title,/75%/);
assert.match(comparison.evidence,/11.09.2026–30.09.2026 \(20 дн.\)/);
assert.deepEqual(comparison.actions[1].clientKeys,['b']);
assert.equal(get({dateFrom:null},'revenue-change'),undefined,'all time has no invented comparison');
assert.match(get({},'revenue-change').title,/нет базы/);
const cases = get({cases:[{clientKey:'lead',status:'open',nextContactDate:'2026-10-19'},{clientKey:'a',status:'closed',nextContactDate:'2026-09-01'},{clientKey:'b',status:'open',nextContactDate:'2026-10-20'},{clientKey:'unknown',status:'open',nextContactDate:'2026-10-19'}]}, 'overdue-cases');
assert.deepEqual(cases.actions[0].clientKeys,['lead'],'includes CRM-only clients, excludes today, closed and unresolved identities');
assert.ok(get({dateTo:'2026-09-01', dateFrom:'2026-08-01',cases:[{clientKey:'lead',status:'open',nextContactDate:'2026-10-19'}]},'overdue-cases'),'CRM always uses today');
const missingCost = get({documents:[doc('a','2026-10-01',10000,null),doc('a','2026-10-02',10000,null),doc('b','2026-09-01',10000,null)]},'incomplete-profit');
assert.deepEqual(missingCost.actions[0].clientKeys,['a']);
assert.match(missingCost.evidence,/период: 2. Клиентов: 1/);
const concentration = get({documents:Array.from({length:8},(_,i)=>doc(`c${i}`,'2026-10-01',i<5?10000:1000))},'concentration');
assert.equal(concentration.actions[0].clientKeys.length,5);
assert.equal(concentration.actions[1].clientKeys.length,3);
assert.equal(concentration.tone,'warning');
assert.match(get({documents:[doc('a','2026-10-01')]},'concentration').recommendation,/Расширьте период/);
assert.deepEqual(build({...base,today:'bad'}),[]);
assert.deepEqual(build({...base,dateFrom:'2026-10-21'}),[]);
assert.match(get({documents:[doc('a','2026-02-30')]},'first-return').title,/пока не оценить/);
assert.ok(build({...base,documents:cohort}).every(i=>i.actions.every(a=>a.clientKeys.length===new Set(a.clientKeys).size)));
console.log('PASS: mature cohorts, same-day duplicates, observation boundaries, equal periods, future documents, CRM-only clients, exact selections, incomplete cost and concentration.');
