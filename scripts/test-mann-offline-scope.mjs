import assert from "node:assert/strict";
import {applicabilityWindow} from "./lib/mann-offline-scope.mjs";
const source={yearFrom:2013,yearTo:2022};
const row={vehicleYears:"09/14 ->",vehicleYearFrom:2014,vehicleYearTo:null};
const window=applicabilityWindow(source,row);
assert.deepEqual(window.intersection,{from:"2014-09",to:"2022-12"});
assert.deepEqual(window.source,{from:"2013-01",to:"2022-12"});
assert.equal(window.restricted,true);
assert.deepEqual(applicabilityWindow({yearFrom:2014,yearTo:2014},row).intersection,{from:"2014-09",to:"2014-12"});
assert.equal(applicabilityWindow({yearFrom:2013,yearTo:2013},row),null);
assert.equal(applicabilityWindow({yearFrom:2022,yearTo:2013},row),null);
assert.equal(applicabilityWindow(source,{...row,vehicleYears:"13/14 ->"}),null);
assert.equal(applicabilityWindow(source,{...row,vehicleYearFrom:2015}),null);
assert.equal(applicabilityWindow(source,{...row,vehicleYears:"2014 onward"}),null);
assert.equal(applicabilityWindow(source,{...row,vehicleYearFrom:null}),null);
assert.equal(applicabilityWindow(source,{...row,vehicleYearTo:2020}),null);
assert.deepEqual(applicabilityWindow({yearFrom:2010,yearTo:null},{vehicleYears:"01/09-06/15",vehicleYearFrom:2009,vehicleYearTo:2015}).intersection,{from:"2010-01",to:"2015-06"});
assert.deepEqual(applicabilityWindow({yearFrom:null,yearTo:2015},{vehicleYears:"01/09-06/15",vehicleYearFrom:2009,vehicleYearTo:2015}).intersection,{from:"2009-01",to:"2015-06"});
assert.equal(applicabilityWindow({yearFrom:2015,yearTo:2016},row).restricted,false);
assert.equal(applicabilityWindow({yearFrom:null,yearTo:null},row),null);
console.log("MANN offline month-scope tests passed");
