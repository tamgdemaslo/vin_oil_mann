import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createJiti} from 'jiti';
import {resolve} from 'node:path';
import {sha,parseCopy} from './lib/mann-offline-scope.mjs';
const root=resolve(import.meta.dirname,'..'),j=createJiti(import.meta.url,{alias:{'@':resolve(root,'src')}});
const {hasContradictoryLegacySourceDate:excluded}=await j.import('../src/lib/mann-source-date-exclusions.ts');
const {buildMannUnifiedTechnicalProfile:profile}=await j.import('../src/lib/mann-unified-technical-profile.ts');
const text=await readFile(resolve(root,'../vin-oil-mann/outputs/podbormasla-20260723/podbormasla_rows.ndjson'),'utf8');
assert.equal(sha(text),'e69dcb74c344c793e4a2cf091077143efb0d332ed24660af7415795b031f01ae');
const raw=text.trim().split('\n').map(JSON.parse);
const old=JSON.parse(await readFile(resolve(root,'outputs/mann-live-audit-1789415211923/revisions.json'),'utf8')).find(r=>r.id==='mtar_a521fb7e3498f84bfd6bec25');
const source=raw.find(r=>r.row_id===old.provenanceJson.sourceRowId);
assert.equal(source.production_years,'до 08. 07. 2019');assert.equal(source.page_sha256,old.provenanceJson.sourcePageHash);
const sql=parseCopy(await readFile('/tmp/vehicle_fluid_requirements.sql','utf8'),'vehicle_fluid_requirements');
const imported=sql.find(s=>s.id===old.sourceRequirementId);assert.equal(imported.sourceRowId,source.row_id);assert.equal(imported.yearFrom,2020);assert.equal(imported.yearTo,2020);
assert.ok(excluded(old));
for(const field of ['sourceRowId','sourceBatchHash','sourcePageHash','sourceAssociationFingerprint'])assert.equal(excluded({...old,provenanceJson:{...old.provenanceJson,[field]:'changed'}}),false);
assert.equal(excluded({...old,sourceRequirementId:'other'}),false);
assert.equal(excluded({...old,applicabilityJson:{...old.applicabilityJson,yearFrom:2018}}),false);
const runtime={...old,createdAt:new Date(old.createdAt)};
assert.equal(profile([runtime],undefined,{engineCode:'CWVB',year:2020}).items.length,0);
assert.equal(profile([{...runtime,reviewConfirmed:true}],undefined,{engineCode:'CWVB',year:2020}).items.length,1);
console.log('Exact legacy raw-date contradiction excluded; changed evidence and reviewed records not overridden.');
