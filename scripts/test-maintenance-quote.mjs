import assert from 'node:assert/strict';
import { createJiti } from 'jiti';
import { resolve } from 'node:path';
const jiti = createJiti(import.meta.url, { alias: { '@': resolve('src') } });
const { matchesQuoteOil, quoteLitresPerUnit, quoteOilAmount, quoteClientText } = await jiti.import('../src/lib/maintenance-quote.ts');
const product = { groupPath: 'Моторные масла', sae: '5W-30', oem: 'VW 504.00', acea: 'C3' };
assert.equal(matchesQuoteOil(product, 'VW 504.00', '5W-30'), true);
assert.equal(matchesQuoteOil(product, 'VW 507.00', '5W-30'), false);
assert.equal(matchesQuoteOil(product, 'VW 504.00', '0W-20'), false);
assert.equal(matchesQuoteOil(product, 'unknown spec', '5W-30'), false);
assert.equal(matchesQuoteOil({ ...product, groupPath: 'Трансмиссионные масла' }, 'VW 504.00', ''), false);
assert.equal(quoteLitresPerUnit({ name: 'Oil 4 л', uomName: 'л', packageVolume: '200' }), 1);
assert.equal(quoteLitresPerUnit({ name: 'Oil', uomName: 'шт.', packageVolume: '4 л' }), 4);
assert.equal(quoteLitresPerUnit({ name: 'Oil 5W-30', uomName: 'шт.' }), null);
const bulk = { id: 'bulk', name: 'Масло на розлив', article: '', price: 900, available: 5, unit: 'л', litresPerUnit: 1, sae: '5W-30', oem: 'VW 504.00' };
assert.deepEqual(quoteOilAmount(bulk, 4.5), { quantity: 4.5, suppliedLitres: 4.5, cents: 405000, enough: true });
const packed = { ...bulk, id: 'packed', unit: 'шт.', litresPerUnit: 4, available: 1 };
assert.deepEqual(quoteOilAmount(packed, 4.5), { quantity: 2, suppliedLitres: 8, cents: 180000, enough: false });
assert.equal(quoteOilAmount(bulk, NaN), null);
const text = quoteClientText('Тестовый автомобиль', 'VW 504.00', 4.5, [bulk, packed], [{ id: 'filter', name: 'Фильтр', quantity: 1, price: 850 }, { id: 'work', name: 'Работа', quantity: 1, price: 1000 }]);
assert.match(text, /Вариант 1/); assert.match(text, /Вариант 2/);
assert.match(text, /5\s900/); assert.match(text, /3\s650/);
assert.match(text, /под заказ/); assert.doesNotMatch(text, /закуп/i);
console.log('maintenance quote: ok');
