import assert from 'node:assert/strict';
import { createJiti } from 'jiti';
import { resolve } from 'node:path';
const jiti = createJiti(import.meta.url, { alias: { '@': resolve('src') } });
const { ownerDashboardPeriod, ownerDashboardDelta } = await jiti.import('../src/lib/owner-dashboard-period.ts');
const period = value => ownerDashboardPeriod(new Date(value), 'Europe/Kaliningrad');
assert.equal(period('2026-11-07T12:00:00Z').previousTo, '2026-10-07');
assert.equal(period('2026-11-07T12:00:00Z').dateFrom, '2026-11-01');
assert.equal(period('2026-11-07T12:00:00Z').dateTo, '2026-11-30');
assert.equal(period('2026-10-31T23:00:00Z').month, '2026-11');
assert.equal(period('2026-03-31T12:00:00Z').previousTo, '2026-02-28');
assert.equal(period('2026-03-31T12:00:00Z').currentComparisonTo, '2026-03-28');
assert.equal(period('2024-03-31T12:00:00Z').previousTo, '2024-02-29');
assert.equal(period('2026-01-07T12:00:00Z').previousFrom, '2025-12-01');
assert.equal(ownerDashboardDelta(150, 100), 50);
assert.equal(ownerDashboardDelta(75, 100), -25);
assert.equal(ownerDashboardDelta(1, 0), null);
assert.equal(ownerDashboardDelta(0, 0), 0);
console.log('Owner dashboard: calendar boundaries, timezone, equal periods, leap year and percentage baseline passed.');
