import assert from 'node:assert/strict';
import {createJiti} from 'jiti';
process.env.APP_TIMEZONE='Europe/Kaliningrad';
const jiti=createJiti(import.meta.url);
const {caseRosskoOrder,withCaseRosskoOrder,validCaseRosskoOrder,caseTimeRemaining}=await jiti.import('../src/lib/client-case-parts.ts');
assert.equal(caseRosskoOrder('Фильтр + прокладка\nЗаказ РОССКО № 196486310'),'196486310');
assert.equal(caseRosskoOrder('196486310 масло на Киа'),'','Unrelated numbers are not silently treated as supplier references');
assert.equal(withCaseRosskoOrder('Фильтр + прокладка\nЗаказ РОССКО № 999','123'),'Заказ РОССКО № 123\nФильтр + прокладка');
assert.equal(withCaseRosskoOrder('Заказ РОССКО № 123\nКомментарий',''),'Комментарий');
assert.equal(withCaseRosskoOrder(null,''),null);
for(const good of ['', ' 123 ', '000123'])assert.ok(validCaseRosskoOrder(good));
for(const bad of [null,123,'abc','123\n999','1'.repeat(21)])assert.equal(validCaseRosskoOrder(bad),false);
const now=new Date('2026-10-23T10:00:00Z');
assert.deepEqual(caseTimeRemaining(new Date('2026-10-23T12:10:00Z'),now),{expired:false,label:'Осталось 2 ч 10 мин'});
assert.deepEqual(caseTimeRemaining(new Date('2026-10-24T13:00:00Z'),now),{expired:false,label:'Осталось 1 дн 3 ч'});
assert.deepEqual(caseTimeRemaining(new Date('2026-10-14T10:00:00Z'),now),{expired:true,label:'Просрочено на 9 дн'});
assert.deepEqual(caseTimeRemaining(now,now),{expired:true,label:'Срок истёк'});
assert.deepEqual(caseTimeRemaining(new Date(+now+30000),now),{expired:false,label:'Осталось менее минуты'});
console.log('CRM parts: supplier reference preserves notes, validates numbers, and shows remaining/overdue durations passed');
