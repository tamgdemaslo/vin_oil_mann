import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createJiti} from 'jiti';
import {sha} from './lib/mann-offline-scope.mjs';
const root=resolve(import.meta.dirname,'..'),dir=resolve(root,'outputs/mann-whole-source-current-recheck-2026-09-14');
const planPath=resolve(root,'outputs/mann-equipment-model-added-preview-2026-09-14/plan.json'),raw=await readFile(planPath,'utf8'),plan=JSON.parse(raw);
assert.equal(sha(raw),'7137c3736b374ebbfc5b4102b79f8b6860228f6e30f3750151f68b5b9219b6ec');
let history=plan.strongSourceDraftHistory;while(history&&!history.reviewEntries?.length)history=history.previous;
assert.equal(history.reviewEntries.length,68);
const existing=new Set(plan.newRevisions.map(r=>r.sourceRequirementId));
const j=createJiti(import.meta.url,{alias:{'@':resolve(root,'src')}}),{mannEquipmentComponentDrives:drivesOf}=await j.import('../src/lib/mann-equipment-scope.ts');
const entries=history.reviewEntries.filter(r=>!existing.has(r.sourceRequirementId)).map(r=>{
 const s=r.originalSource,text=(s.componentModel??'').trim(),label=s.systemNameRaw??'';
 let group;
 if(r.reasons.includes('PROTECTED_LIVE_REVISION'))group='PROTECTED_LIVE_REVIEW_ONLY';
 else if(drivesOf(text))group='EXPLICIT_COMPONENT_DRIVE_BRANCHES';
 else if(/HALDEX/i.test(text+' '+label))group='HALDEX_TYPE_AND_LABEL_EVIDENCE';
 else if(/LSD/i.test(text+' '+label))group='LIMITED_SLIP_CONFIRMATION_REQUIRED';
 else if(/\*|используется|л\.с\./i.test(text))group='GEARBOX_ENGINE_POWER_QUALIFIERS';
 else if(/\/\s*\d{4}-\d{4}$/.test(text))group='GEARBOX_MODEL_AND_YEAR_BRANCH';
 else if(/\([^)]*\)/.test(text))group='GEARBOX_PARENTHETICAL_DESCRIPTOR';
 else if(/DSG|DCT/.test(label))group='GEARBOX_CIRCUIT_AND_COUNT_LABEL';
 else if(/^(?:\d+AT|\d+DCT)$/.test(text))group='GEARBOX_TYPE_COUNT_NOT_MODEL';
 else if(/Сервоусилитель руля/i.test(label))group='STEERING_LABEL_DESCRIPTOR';
 else if(/РЕДУКТОР ЗАДНЕГО МОСТА/i.test(label))group='REAR_AXLE_LABEL_AND_SOURCE_DRIVE';
 else if(s.driveType)group='EXPLICIT_SOURCE_DRIVE_SCOPE';
 else group='OTHER_SYSTEM_POLICY';
 return {...r,group,sourceHash:sha(s),parsedDriveBranches:drivesOf(text),requiresFreshSourcePreflight:true,publicationAllowed:false};
});
assert.equal(entries.length,45);assert.equal(new Set(entries.map(r=>r.sourceRequirementId)).size,45);
const counts=Object.fromEntries([...Map.groupBy(entries,r=>r.group)].map(([k,v])=>[k,v.length]));
const report={planPath,planHash:sha(raw),sourceReviewCount:68,alreadyScopedSources:23,remaining:entries.length,groups:counts,entries,productionApplyAllowed:false,limitation:'Routing only; no source fact approval. Existing scoped candidates still retain pending intervals. Groups preserve every original source and overlapping review reason.'};
await writeFile(resolve(dir,'remaining-policy-review-batches-v1.json'),JSON.stringify(report,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({remaining:entries.length,groups:counts}));
