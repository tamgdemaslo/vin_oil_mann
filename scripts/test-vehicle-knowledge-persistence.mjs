import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {createJiti} from 'jiti';
const mock = resolve('scripts/fixtures/vehicle-knowledge-mocks.mjs');
const j = createJiti(import.meta.url, {alias:{'@':resolve('src'),'@/lib/db':mock,'@/lib/request-tenant-store':mock,'@/lib/integrations/tronk/client':mock}});
const {lookupVehicle} = await j.import('../src/lib/vehicle-identity.ts');
const {getVinLookupCache,setVinLookupCache} = await j.import('../src/lib/vin-lookup-cache.ts');
const s = globalThis.vehicleKnowledgeTest = {rows:[],paid:0,payload:{decoded:{make:'FORD',model:'Mondeo'},oilInfo:null}};
const input = {organizationId:'test-org',inputType:'vin',input:'WF0FXXWPCFJT12345'};
await lookupVehicle(input);
assert.ok(s.rows.length);
assert.ok(s.rows.every(row => row.expiresAt.getUTCFullYear() === 9999));
const paid = s.paid;
for (const row of s.rows) row.expiresAt = new Date('2020-01-01');
assert.equal((await lookupVehicle(input)).fromCache,true);
assert.equal(s.paid,paid,'legacy expired TRONK answers are reused');
await lookupVehicle({...input,refresh:true});
assert.ok(s.paid>paid,'explicit refresh still works');
await lookupVehicle({...input,organizationId:'other-org'});
assert.equal(s.where.organizationId,'other-org','organization scope preserved');
assert.deepEqual(await getVinLookupCache(input.input),s.payload);
assert.doesNotMatch(s.sql,/expires_at\s*>/);
await setVinLookupCache(input.input,s.payload);
assert.equal(s.writeValues.at(-1).getUTCFullYear(),9999);
s.failWrite = true;
await assert.rejects(lookupVehicle({...input,refresh:true}),/Не удалось сохранить/);
await assert.rejects(setVinLookupCache(input.input,s.payload),/Не удалось сохранить/);
console.log('PASS durable TRONK and VIN knowledge, expired legacy records, explicit refresh, organization scope');
